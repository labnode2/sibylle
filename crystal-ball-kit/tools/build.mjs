// Builds the kit from src/crystal-ball.js: the classic-script copy (dist/crystal-ball.global.js),
// and every asset (favicons, SVGs, PNGs, sprite sheets). Run it after changing a design:
//   node tools/build.mjs
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { deflateSync } from 'node:zlib';
import * as ball from '../src/crystal-ball.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = (path, data) => {
  mkdirSync(dirname(join(root, path)), { recursive: true });
  writeFileSync(join(root, path), data);
};

// The same code as a classic script that sets window.CrystalBall, for pages without a bundler.
const source = readFileSync(join(root, 'src/crystal-ball.js'), 'utf8');
const names = [...source.matchAll(/^export (?:const|function) (\w+)/gm)].map((m) => m[1]);
out(
  'dist/crystal-ball.global.js',
  `// Generated by tools/build.mjs from src/crystal-ball.js: do not edit.\n(function (root) {\n${source.replace(/^export (const|function) /gm, '$1 ')}\nroot.CrystalBall = { ${names.join(', ')} };\n})(typeof window !== 'undefined' ? window : globalThis);\n`,
);

// PNG: 8-bit RGBA, no filter.
const CRC = Array.from({ length: 256 }, (_, n) => {
  let c = n;
  for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
  return c >>> 0;
});
function crc32(buf) {
  let c = 0xffffffff;
  for (const b of buf) c = CRC[(c ^ b) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}
function chunk(type, data) {
  const head = Buffer.alloc(8);
  head.writeUInt32BE(data.length, 0);
  head.write(type, 4, 'ascii');
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(Buffer.concat([head.subarray(4), data])), 0);
  return Buffer.concat([head, data, crc]);
}
function png(width, height, rgba) {
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(width, 0);
  ihdr.writeUInt32BE(height, 4);
  ihdr.set([8, 6, 0, 0, 0], 8);
  const raw = Buffer.alloc((width * 4 + 1) * height);
  for (let y = 0; y < height; y++) Buffer.from(rgba.buffer, rgba.byteOffset + y * width * 4, width * 4).copy(raw, y * (width * 4 + 1) + 1);
  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk('IHDR', ihdr),
    chunk('IDAT', deflateSync(raw)),
    chunk('IEND', Buffer.alloc(0)),
  ]);
}
const framePNG = (grid, scale) => png(16 * scale, 16 * scale, ball.toRGBA(grid, scale));

// A sprite sheet: every frame of one loop side by side, for a CSS steps() animation.
function sheet(id, scale) {
  const n = ball.frameCount(id);
  const w = 16 * scale;
  const rgba = new Uint8Array(w * n * w * 4);
  for (let f = 0; f < n; f++) {
    const one = ball.toRGBA(ball.frame(id, f), scale);
    for (let y = 0; y < w; y++) rgba.set(one.subarray(y * w * 4, (y + 1) * w * 4), (y * w * n + f * w) * 4);
  }
  return png(w * n, w, rgba);
}

// ICO with PNG images inside (every current browser and OS reads them).
function ico(images) {
  const head = Buffer.alloc(6 + 16 * images.length);
  head.writeUInt16LE(1, 2);
  head.writeUInt16LE(images.length, 4);
  let offset = head.length;
  images.forEach(([size, data], i) => {
    const e = 6 + 16 * i;
    head[e] = size;
    head[e + 1] = size;
    head.writeUInt16LE(1, e + 4);
    head.writeUInt16LE(32, e + 6);
    head.writeUInt32LE(data.length, e + 8);
    head.writeUInt32LE(offset, e + 12);
    offset += data.length;
  });
  return Buffer.concat([head, ...images.map(([, data]) => data)]);
}

rmSync(join(root, 'assets'), { recursive: true, force: true });

const fixed = ball.frame('fixed');
out('assets/favicon/favicon.svg', ball.toSVG(fixed));
out('assets/favicon/favicon.ico', ico([16, 32, 48].map((s) => [s, framePNG(fixed, s / 16)])));
for (const [name, scale] of [['favicon-16.png', 1], ['favicon-32.png', 2], ['favicon-48.png', 3], ['icon-192.png', 12], ['icon-512.png', 32]]) {
  out(`assets/favicon/${name}`, framePNG(fixed, scale));
}
// Apple's touch icon is opaque: the ball on the dark canvas, 10 px per ball pixel, centered.
const touch = new Uint8Array(180 * 180 * 4);
for (let i = 0; i < touch.length; i += 4) touch.set([0x11, 0x12, 0x14, 255], i);
const big = ball.toRGBA(fixed, 10);
for (let y = 0; y < 160; y++) {
  for (let x = 0; x < 160; x++) {
    const s = (y * 160 + x) * 4;
    if (big[s + 3]) touch.set(big.subarray(s, s + 4), ((y + 10) * 180 + x + 10) * 4);
  }
}
out('assets/favicon/apple-touch-icon.png', png(180, 180, touch));

for (const id of ball.variants()) {
  const first = ball.frame(id);
  out(`assets/svg/${id}.svg`, ball.toSVG(first));
  out(`assets/png/${id}.png`, framePNG(first, 8));
  if (ball.frameCount(id) > 1) {
    out(`assets/sprites/${id}.png`, sheet(id, 1));
    out(`assets/sprites/${id}@4x.png`, sheet(id, 4));
  }
}
console.log(`built dist/crystal-ball.global.js and the assets of ${ball.variants().length} variants`);
