export type EditorIcon = keyof typeof DRAWINGS;

function path(rows: readonly string[]): string {
  let d = '';
  rows.forEach((row, y) => {
    for (const match of row.matchAll(/#+/g)) {
      d += `M${match.index} ${y}h${match[0].length}v1h-${match[0].length}z`;
    }
  });
  return d;
}

export const EDITOR_ICONS = Object.fromEntries(
  Object.entries(DRAWINGS).map(([name, rows]) => [name, path(rows)]),
) as Record<EditorIcon, string>;
